#!/usr/bin/env python3
"""Compile a single client-page CSS object from canonical type roles and local layout."""
from pathlib import Path
import re,sys
repo=Path(__file__).resolve().parents[1];root=repo/'site'
master=(root/'assets/css/fibonacci.css').read_text()
fonts='\n'.join(re.findall(r'@font-face\s*\{[^{}]*\}',master))
roots=[s for s in re.findall(r':root\s*\{[^{}]*\}',master) if '--text-xs:' in s or '--fib-8:' in s]
roots='\n'.join(roots)
# Strict local Fibonacci roles are derived from the same canonical spacing anchors.
alias={'xs':'13','sm':'13','base':'21','md':'21','lg':'21','xl':'34','2xl':'55','3xl':'89'}
for name,n in alias.items():roots=re.sub(r'--text-'+name+r'\s*:[^;]+;',f'--text-{name}:var(--fib-{n});',roots)
roles=master.split('/* Explicit roles separate semantic heading levels from visual presentation. */',1)[1].split('/* The existing homepage first viewport',1)[0]
nav=(root/'assets/navigation.css').read_text();footer=(root/'assets/footer.css').read_text()
# Compile component geometry onto the requested local spacing ladder.
for old,new in [('24px','21px'),('40px','34px'),('26px','21px'),('16px','13px'),('68px','89px'),('44px','55px'),('outline-offset:4px','outline-offset:8px')]:
 nav=nav.replace(old,new);footer=footer.replace(old,new)
text='/* Generated by tools/build_clients_css.py. Edit canonical type tokens or tools/clients/layout.css. */\n'+fonts+'\n'+roots+'\n'+roles+'\n'+nav+'\n'+footer+'\n'+(repo/'tools/clients/layout.css').read_text()
# All corners and surfaces are structural. Runtime CSS contains no imports.
text=re.sub(r'/\*.*?\*/','',text,flags=re.S).strip()+'\n'
target=root/'assets/clients-monolith.css'
if '--check' in sys.argv:
 if not target.exists() or target.read_text()!=text:raise SystemExit('Clients CSS bundle is stale; run tools/build_clients_css.py')
 print('Validated deterministic single-file clients CSS bundle.')
else:target.write_text(text);print(f'Compiled clients CSS: {len(text.encode())} bytes.')
